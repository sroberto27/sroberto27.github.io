#!/usr/bin/env bash
# run-all.sh -- run every scan, write the evidence, summarise.
#
#   run-all.sh [--target <url>] [--offline] [--only <prefix>...]
#
# This is an evidence collector, not a gate. It exits 0 even when every check
# fires, because deciding what any of it means is the model's job and the
# operator's call -- not a shell script's.
#
# Output: scan/results/<YYYY-MM-DD>/<script>.txt plus SUMMARY.md.
#
# Read SUMMARY.md's tool matrix BEFORE reading any result. A DEGRADED check
# ran through a fallback and is weaker than the real tool; reporting it as a
# clean pass is the specific failure this whole status vocabulary exists to
# prevent.

SELF_DIR="$(cd "$(dirname "$0")" && pwd)"

# ---------------------------------------------------------------------------
# Parse args before sourcing common.sh, since they set the variables it reads.
ONLY=""
while [ $# -gt 0 ]; do
  case "$1" in
    --target) DTS_AUDIT_TARGET="$2"; export DTS_AUDIT_TARGET; shift 2 ;;
    --target=*) DTS_AUDIT_TARGET="${1#*=}"; export DTS_AUDIT_TARGET; shift ;;
    --offline) DTS_AUDIT_OFFLINE=1; export DTS_AUDIT_OFFLINE; shift ;;
    --only) ONLY="$ONLY $2"; shift 2 ;;
    -h|--help)
      sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *) printf 'unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done

. "$SELF_DIR/lib/common.sh"

RUN_DATE="$(date -u +%Y-%m-%d)"
RESULTS="$SCAN_DIR/results/$RUN_DATE"
mkdir -p "$RESULTS"

SCRIPTS="00-inventory 10-deps 20-secrets 30-rls 40-supabase-cfg 50-headers 55-deploy-exposure 60-cors"

# ---------------------------------------------------------------------------
banner "run-all -- full scan pass"
tool_matrix

printf '\n  results -> %s\n' "$RESULTS"
if [ "$OFFLINE" = "1" ]; then
  printf '  OFFLINE: 10/40/50/55/60 will skip their network checks. 55 in\n'
  printf '  particular has no offline equivalent -- what is on disk says nothing\n'
  printf '  about what was uploaded.\n'
fi

# ---------------------------------------------------------------------------
run_one() {
  local name="$1"
  local script="$SCAN_DIR/$name.sh"
  local out="$RESULTS/$name.txt"

  if [ ! -f "$script" ]; then
    printf '  %-20s MISSING (%s)\n' "$name" "$script"
    return
  fi

  local started
  started="$(date -u +%H:%M:%S)"
  # Never abort the pass on one script's failure: a broken check is itself
  # evidence, and the later scripts are independent of it.
  bash "$script" >"$out" 2>&1
  local rc=$?

  local ok lead deg skip err
  ok="$(grep -c '^\[OK' "$out" 2>/dev/null)"
  lead="$(grep -c '^\[LEAD' "$out" 2>/dev/null)"
  deg="$(grep -c '^\[DEGRADED' "$out" 2>/dev/null)"
  skip="$(grep -c '^\[SKIPPED' "$out" 2>/dev/null)"
  err="$(grep -c '^\[ERROR' "$out" 2>/dev/null)"

  printf '  %-20s %s  ok=%-3s lead=%-3s degraded=%-3s skipped=%-3s error=%-3s exit=%s\n' \
    "$name" "$started" "$ok" "$lead" "$deg" "$skip" "$err" "$rc"

  printf '%s|%s|%s|%s|%s|%s|%s\n' "$name" "$ok" "$lead" "$deg" "$skip" "$err" "$rc" \
    >> "$RESULTS/.tally"
}

section "Running"
rm -f "$RESULTS/.tally"
for s in $SCRIPTS; do
  if [ -n "$ONLY" ]; then
    case " $ONLY " in *" $s "*) ;; *) continue ;; esac
  fi
  run_one "$s"
done

# ---------------------------------------------------------------------------
# SUMMARY.md
SUMMARY="$RESULTS/SUMMARY.md"
{
  printf '# Scan summary -- %s\n\n' "$RUN_DATE"
  printf '_Generated by `scan/run-all.sh`. Evidence, not findings._\n\n'

  printf '## Run context\n\n'
  printf '| | |\n|---|---|\n'
  printf '| target | `%s` |\n' "$TARGET"
  printf '| offline | %s |\n' "$([ "$OFFLINE" = "1" ] && echo yes || echo no)"
  printf '| project | `%s` |\n' "$PROJECT_DIR"
  printf '| git root | `%s` (scoped to `%s`) |\n' "$GIT_ROOT" "$PROJECT_REL"
  printf '| commit | `%s` |\n' "$(pgit log -1 --format='%h %s' -- "$PROJECT_REL" 2>/dev/null)"
  printf '| working tree | %s uncommitted file(s) |\n' \
    "$(pgit status --porcelain -- "$PROJECT_REL" 2>/dev/null | wc -l | tr -d ' ')"
  printf '| run at (UTC) | %s |\n\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"

  dirtyn="$(pgit status --porcelain -- "$PROJECT_REL" 2>/dev/null | wc -l | tr -d ' ')"
  if [ "${dirtyn:-0}" -gt 0 ]; then
    printf '> The working tree is dirty. Probes against the deployed target and\n'
    printf '> greps against local files describe different versions of the site.\n'
    printf '> Read any disagreement between them as drift, not as a finding.\n\n'
  fi

  printf '## Tool availability\n\n'
  printf '| tool | state |\n|---|---|\n'
  for t in git rg node npm npx curl gitleaks osv-scanner psql supabase jq semgrep; do
    if have "$t"; then printf '| `%s` | present |\n' "$t"
    else printf '| `%s` | **absent** -- %s |\n' "$t" "$(tool_install_hint "$t")"; fi
  done
  printf '\nChecks that fell back to a native equivalent are marked `DEGRADED` in\n'
  printf 'the per-script output. A DEGRADED result is weaker than the real tool\n'
  printf 'and must never be reported as a clean pass.\n\n'

  printf '## Results by script\n\n'
  printf '| script | OK | LEAD | DEGRADED | SKIPPED | ERROR | exit |\n'
  printf '|---|---|---|---|---|---|---|\n'
  if [ -f "$RESULTS/.tally" ]; then
    while IFS='|' read -r n ok lead deg skip err rc; do
      printf '| [`%s`](%s.txt) | %s | %s | %s | %s | %s | %s |\n' \
        "$n" "$n" "$ok" "$lead" "$deg" "$skip" "$err" "$rc"
    done < "$RESULTS/.tally"
  fi

  printf '\n## Every LEAD, in one place\n\n'
  printf 'A LEAD is deliberately not a FINDING. It is a place to look. Findings\n'
  printf 'on this project have dissolved on inspection before, so nothing below\n'
  printf 'goes in a report until it has been re-verified by reading the real code\n'
  printf 'or re-running the real request.\n\n'
  found_lead=0
  for s in $SCRIPTS; do
    f="$RESULTS/$s.txt"
    [ -f "$f" ] || continue
    leads="$(grep '^\[LEAD' "$f" 2>/dev/null)"
    [ -z "$leads" ] && continue
    found_lead=1
    printf '### %s\n\n```\n%s\n```\n\n' "$s" "$leads"
  done
  [ "$found_lead" = "0" ] && printf '_No leads recorded._\n\n'

  printf '## Checks that did not run\n\n'
  printf 'These are unanswered questions, not passes. Say so in the report.\n\n'
  found_skip=0
  for s in $SCRIPTS; do
    f="$RESULTS/$s.txt"
    [ -f "$f" ] || continue
    sk="$(grep -E '^\[(SKIPPED|ERROR)' "$f" 2>/dev/null)"
    [ -z "$sk" ] && continue
    found_skip=1
    printf '### %s\n\n```\n%s\n```\n\n' "$s" "$sk"
  done
  [ "$found_skip" = "0" ] && printf '_Every check ran._\n\n'

  printf '## Next step\n\n'
  printf 'Do not audit every scope by reflex. Read the leads above, decide which\n'
  printf 'scopes they actually point at, and run those one at a time:\n\n'
  printf '%s\n' '- `supabase` -- RLS logic, policy correctness, storage, auth config'
  printf '%s\n' '- `cloudflare` -- deploy exposure, headers, cache, bindings, WAF'
  printf '%s\n' '- `app` -- authz, IDOR, injection, XSS sinks, CSRF'
  printf '%s\n' '- `deps` -- advisories plus reachability triage'
} > "$SUMMARY"

rm -f "$RESULTS/.tally"

# ---------------------------------------------------------------------------
section "Done"
printf '  summary : %s\n' "$SUMMARY"
printf '  evidence: %s/*.txt\n\n' "$RESULTS"
printf '  Read the tool matrix in SUMMARY.md before reading any result.\n'
printf '  Then triage the leads -- they are places to look, not findings.\n'
exit 0
