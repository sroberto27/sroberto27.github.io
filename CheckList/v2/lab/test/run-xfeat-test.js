/* End-to-end validation of the browser pipeline WITHOUT a browser.

   Consumes raw XFeat ONNX outputs recorded from views rendered off a
   synthetic panorama at known rotations and a known focal length, then
   drives the REAL browser-side code -- the same detectKeypoints,
   sampleDescriptors, matcher and geometry that ship in lab/ -- and
   checks the recovered geometry against the ground truth.

   This is the "prove it in isolation before touching the stitcher" step.
   The only thing it cannot cover is onnxruntime-web itself, which needs
   a real device.

   Fixture: generated by tools/xfeat_fixture.py (see FIXTURE below).
   Run:     node lab/test/run-xfeat-test.js [fixtureDir]
*/
const fs = require('fs');
const path = require('path');
const { load } = require('./load.js');

const FIXTURE = process.argv[2] ||
  path.join(process.env.TEMP || '/tmp', 'xfeat_fixture');

if (!fs.existsSync(path.join(FIXTURE, 'meta.json'))) {
  console.log('No fixture at ' + FIXTURE);
  console.log('Generate one with tools/xfeat_fixture.py, or pass a directory.');
  process.exit(0);
}

['pano/so3.js', 'pano/camera.js', 'pano/estimate.js', 'pano/calibrate.js',
 'pano/bundle.js', 'pano/pipeline.js', 'lab/test/synth.js'].forEach(load);
// Browser modules: the IIFE bodies only touch document/ort inside the
// functions we are not calling, so they load cleanly here.
load('pano/xfeat-extractor.js');
load('pano/xfeat-match.js');

const S = globalThis.LSCSO3, C = globalThis.LSCCamera, P = globalThis.LSCPipeline;
const XF = globalThis.LSCXFeat, MM = globalThis.LSCMatch, Synth = globalThis.LSCSynth;

let failures = 0, checks = 0;
function check(name, cond, detail) {
  checks++; if (!cond) failures++;
  console.log('  [' + (cond ? 'PASS' : 'FAIL') + '] ' + name + (detail ? '  ' + detail : ''));
}
const fmt = (v, d) => Number(v).toFixed(d === undefined ? 3 : d);

const meta = JSON.parse(fs.readFileSync(path.join(FIXTURE, 'meta.json'), 'utf8'));
const W = meta.width, H = meta.height;

console.log('=== 1. Feature extraction (real model outputs -> JS post-processing) ===');
const features = [];
for (let i = 0; i < meta.files.length; i++) {
  const buf = fs.readFileSync(path.join(FIXTURE, meta.files[i]));
  const netW = buf.readInt32LE(0), netH = buf.readInt32LE(4);
  const gw = buf.readInt32LE(8), gh = buf.readInt32LE(12);
  let off = 16;
  const heat = new Float32Array(buf.buffer, buf.byteOffset + off, netW * netH);
  off += netW * netH * 4;
  const desc = new Float32Array(buf.buffer, buf.byteOffset + off, 64 * gw * gh);

  const opts = Object.assign({}, XF.DEFAULTS);
  const kps = XF.detectKeypoints(heat, netW, netH, opts);
  const descriptors = XF.sampleDescriptors(desc, gw, gh, kps);
  const sx = W / netW, sy = H / netH;
  features.push({
    keypoints: kps.map(k => ({ x: k.x * sx, y: k.y * sy, score: k.score })),
    descriptors, width: W, height: H, count: kps.length
  });
}
const counts = features.map(f => f.count);
console.log('    keypoints per view: ' + counts.join(', '));

// Descriptors must be unit norm or the dot-product matcher is meaningless.
let worstNorm = 0;
for (const f of features) {
  for (let k = 0; k < Math.min(f.count, 50); k++) {
    let n = 0;
    for (let c = 0; c < 64; c++) { const v = f.descriptors[k * 64 + c]; n += v * v; }
    worstNorm = Math.max(worstNorm, Math.abs(Math.sqrt(n) - 1));
  }
}
check('every view produced keypoints', counts.every(c => c > 100), '(min ' + Math.min(...counts) + ')');
check('descriptors are L2-normalised', worstNorm < 1e-5, '(max deviation ' + worstNorm.toExponential(1) + ')');

console.log('\n=== 2. Matching under the pose prior ===');
const truePoses = meta.views;
const trueR = truePoses.map(p => S.fromYawPitchRoll(p.yaw, p.pitch, p.roll));

// Simulate the sensor: anisotropic error plus accumulating yaw drift.
const rnd = Synth.makeRng(5);
const D = Math.PI / 180;
const priors = truePoses.map((p, i) => ({
  yaw: p.yaw + (i / (truePoses.length - 1)) * 5 * D + Synth.gauss(rnd) * 2.5 * D,
  pitch: p.pitch + Synth.gauss(rnd) * 0.35 * D,
  roll: p.roll + Synth.gauss(rnd) * 0.35 * D
}));
const priorR = priors.map(p => S.fromYawPitchRoll(p.yaw, p.pitch, p.roll));
const nominalFocal = C.focalFromHFov(68 * D, W);

const pairs = P.candidatePairs(priors, {});
const edgeInputs = [];
let gatedComparisons = 0, plainComparisons = 0, gatedMatches = 0, plainMatches = 0;

for (const pr of pairs) {
  const Rrel = S.mul(S.transpose(priorR[pr.j]), priorR[pr.i]);
  const gatedRes = MM.match(features[pr.i], features[pr.j], {
    predict: MM.makePredictor(Rrel, W, H, nominalFocal, S, C),
    searchRadius: Math.max(120, nominalFocal * 9 * D),
    ratio: 0.92, minScore: 0.5
  });
  const plainRes = MM.match(features[pr.i], features[pr.j], { ratio: 0.92, minScore: 0.5 });
  gatedComparisons += gatedRes.stats.comparisons;
  plainComparisons += plainRes.stats.comparisons;
  gatedMatches += gatedRes.matches.length;
  plainMatches += plainRes.matches.length;
  if (gatedRes.matches.length >= 6) edgeInputs.push({ i: pr.i, j: pr.j, matches: gatedRes.matches });
}

console.log('    pairs matched          ' + pairs.length);
console.log('    gated    ' + (gatedComparisons / 1e6).toFixed(1) + 'M comparisons, ' + gatedMatches + ' matches');
console.log('    exhaustive ' + (plainComparisons / 1e6).toFixed(1) + 'M comparisons, ' + plainMatches + ' matches');
console.log('    speedup                ' + fmt(plainComparisons / gatedComparisons, 1) + 'x fewer comparisons');

check('prior gating cuts descriptor comparisons by >3x',
  plainComparisons / gatedComparisons > 3, '(' + fmt(plainComparisons / gatedComparisons, 1) + 'x)');
check('gating does not lose most matches',
  gatedMatches > plainMatches * 0.5, '(' + gatedMatches + ' vs ' + plainMatches + ')');
check('enough usable edges for a ring', edgeInputs.length >= 6, '(' + edgeInputs.length + ')');

console.log('\n=== 3. Geometry from real descriptors ===');
const before = Synth.poseError(priorR, trueR);
const res = P.refinePoses({ width: W, height: H, priors, edges: edgeInputs }, {});
check('pipeline succeeded', res.ok === true, res.ok ? '' : '(' + res.reason + ')');

if (res.ok) {
  const after = Synth.poseError(res.rotations, trueR);
  const fovErr = Math.abs(res.hFovDeg - meta.trueHFovDeg);
  const rings = P.ringDiagnostics(res.rotations, res.edges);

  console.log('    true hFOV              ' + fmt(meta.trueHFovDeg, 2) + ' deg  (app assumes 68.00)');
  console.log('    recovered hFOV         ' + fmt(res.hFovDeg, 2) + ' deg  (err ' + fmt(fovErr, 2) + ' deg)');
  console.log('    match spread           ' + fmt(res.calibration.spread.mean, 2) + '  (focal conditioning)');
  console.log('    pose err before        mean ' + fmt(before.meanDeg) + ' deg');
  console.log('    pose err after         mean ' + fmt(after.meanDeg) + ' deg, max ' + fmt(after.maxDeg) + ' deg');
  console.log('    edges used             ' + res.edges.length + ', ' + res.rejected.length + ' rejected');
  console.log('    mean inlier ratio      ' + fmt(res.edges.reduce((s, e) => s + e.inlierRatio, 0) / res.edges.length, 2));
  console.log('    rms edge residual      ' + fmt(res.bundle.rmsEdgeResidualRad * 180 / Math.PI, 4) + ' deg');
  console.log('    horizon loop drift     ' + (rings.horizon.measured === null ? 'n/a' : fmt(rings.horizon.measured, 3) + ' deg'));

  check('focal recovered within 3% of truth',
    fovErr / meta.trueHFovDeg * 100 < 3, '(' + fmt(fovErr / meta.trueHFovDeg * 100, 2) + '%)');
  check('beats the hardcoded 68 deg assumption',
    fovErr < Math.abs(68 - meta.trueHFovDeg));
  check('mean pose error below 0.5 deg', after.meanDeg < 0.5, '(' + fmt(after.meanDeg) + ' deg)');
  check('refinement improves on the sensor prior by >3x',
    before.meanDeg / after.meanDeg > 3, '(' + fmt(before.meanDeg / after.meanDeg, 1) + 'x)');
  check('inlier ratios are healthy',
    res.edges.reduce((s, e) => s + e.inlierRatio, 0) / res.edges.length > 0.5);
}

console.log('\n' + '-'.repeat(58));
console.log(failures === 0 ? 'ALL ' + checks + ' CHECKS PASSED'
  : failures + ' of ' + checks + ' CHECKS FAILED');
console.log('-'.repeat(58));
process.exit(failures === 0 ? 0 : 1);
